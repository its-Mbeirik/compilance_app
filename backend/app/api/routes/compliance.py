"""Compliance verification endpoints."""

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel
from typing import List, Optional
from enum import Enum

router = APIRouter()


class SeverityLevel(str, Enum):
    """Severity levels for compliance issues."""

    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    INFO = "info"


class ComplianceIssue(BaseModel):
    """A single compliance issue detected."""

    issue_id: str
    severity: SeverityLevel
    clause_reference: str
    issue_type: str  # "missing_clause", "non_compliant", "contradiction", etc.
    description: str
    legal_reference: str  # Law/article number
    recommendation: str


class ComplianceReport(BaseModel):
    """Full compliance report for a contract."""

    contract_id: str
    document_type: str
    analysis_date: str
    overall_status: str  # "compliant", "non_compliant", "partially_compliant"
    compliance_score: float  # 0-100
    total_issues: int
    critical_issues: int
    high_issues: int
    issues: List[ComplianceIssue]
    summary: str
    recommendations: List[str]


